CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255),
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL
);

CREATE TABLE exercise (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL UNIQUE,
    description  VARCHAR(255),
    exercise_category VARCHAR(255) NOT NULL
        CONSTRAINT exercise_exercise_category_check
        CHECK (exercise_category IN ('CHEST', 'BACK', 'LEGS', 'SHOULDERS', 'ARMS', 'CORE')),
    target_muscle VARCHAR(255) NOT NULL
        CONSTRAINT exercise_target_muscle_check
        CHECK (target_muscle IN ('CHEST', 'UPPER_BACK', 'LATS', 'FRONT_DELTS', 'SIDE_DELTS', 'REAR_DELTS', 'CALVES', 'QUADS', 'HAMSTRINGS', 'ABS', 'BICEPS', 'TRICEPS', 'GLUTES', 'ADDUCTORS'))
);

CREATE TABLE workout (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id),
    name         VARCHAR(255)  NOT NULL,
    status       VARCHAR(255)  NOT NULL DEFAULT 'PENDING'
        CONSTRAINT workout_status_check
        CHECK (status IN ('PENDING', 'ACTIVE', 'COMPLETED')),
    scheduled_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    comments     VARCHAR(255),
    created_at   TIMESTAMPTZ   NOT NULL,
    updated_at   TIMESTAMPTZ   NOT NULL,
    volume       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_sets   INTEGER       NOT NULL DEFAULT 0
);

CREATE INDEX idx_workout_user_scheduled ON workout (user_id, scheduled_at);

CREATE TABLE workout_exercise (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id  BIGINT        NOT NULL REFERENCES workout (id) ON DELETE CASCADE,
    exercise_id BIGINT        NOT NULL REFERENCES exercise (id),
    sets        INTEGER       NOT NULL,
    reps        INTEGER       NOT NULL,
    weight_kg   NUMERIC(6, 2),
    order_index INTEGER       NOT NULL
);

CREATE INDEX idx_workout_exercise_workout ON workout_exercise (workout_id);
CREATE INDEX idx_workout_exercise_exercise ON workout_exercise (exercise_id);
